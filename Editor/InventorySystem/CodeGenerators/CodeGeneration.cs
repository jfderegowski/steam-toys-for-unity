using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace SteamToys.Editor.InventorySystem.CodeGenerators
{
    /// <summary>
    /// Writes the scripts of <see cref="CodeGenerator"/>s. Each script it wrote last is moved to its new path when the
    /// name or the folder changed, so the old one is not left behind; a file it did not write is never written over;
    /// and a script a generator no longer writes stops it until it is deleted or kept as a script of the game, since
    /// assets of its class would lose it, and left to the generator it would name types a rename takes away.
    /// </summary>
    internal static class CodeGeneration
    {
        #region Constants

        private const string GENERATED_MARKER = "Generated by ";

        // PascalCase: a capital first letter keeps clear of the C# keywords, and without underscores every name has
        // one snake_case form that reads back to it.
        private static readonly Regex NamePattern = new("^[A-Z][A-Za-z0-9]*$");
        private static readonly Regex NamespacePattern = new("^[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)*$");
        private static readonly Regex AssetMenuPattern = new("^[A-Za-z0-9 _\\-/]*$");

        #endregion

        #region Generate

        /// <summary>
        /// Writes the scripts of <paramref name="generators"/> that have no problems, importing them together so they
        /// compile once. Returns the paths written.
        /// </summary>
        public static List<string> Generate(IEnumerable<CodeGenerator> generators)
        {
            var written = new List<(CodeGenerator generator, ScriptSpec spec, string path)>();

            foreach (var generator in generators)
            {
                var problems = GetProblems(generator);

                if (problems.Count > 0)
                {
                    Debug.LogError($"{generator.DisplayName}: not generated.\n{string.Join("\n", problems)}");
                    continue;
                }

                if (!MoveScripts(generator))
                    continue;

                written.AddRange(generator.GetScriptSpecs().Select(spec => (generator, spec, GetScriptPath(generator, spec.FileName))));
            }

            AssetDatabase.StartAssetEditing();

            try
            {
                foreach (var (generator, spec, path) in written)
                {
                    File.WriteAllText(path, GetHeader(generator) + "\n" + WrapInNamespace(generator.Namespace, spec.BuildBody()));
                    AssetDatabase.ImportAsset(path);
                }
            }
            finally
            {
                AssetDatabase.StopAssetEditing();
            }

            foreach (var (generator, spec, path) in written)
                generator.SetScript(spec.Key, AssetDatabase.LoadAssetAtPath<TextAsset>(path));

            SteamItemDefinitions.instance.SaveDefinitions();

            if (written.Count > 0)
                Debug.Log($"Generated {string.Join(", ", written.Select(script => script.path))}.");

            return written.Select(script => script.path).ToList();
        }

        // Moved, not written anew, so a script keeps its GUID and nothing is left at the old path.
        private static bool MoveScripts(CodeGenerator generator)
        {
            foreach (var spec in generator.GetScriptSpecs())
            {
                var oldPath = GetGeneratedPath(generator, spec.Key);
                var path = GetScriptPath(generator, spec.FileName);

                CreateFolder(Path.GetDirectoryName(path)!.Replace('\\', '/'));

                if (string.IsNullOrEmpty(oldPath) || oldPath == path)
                    continue;

                var error = AssetDatabase.MoveAsset(oldPath, path);

                if (string.IsNullOrEmpty(error))
                    continue;

                Debug.LogError($"{generator.DisplayName}: could not move {oldPath} to {path}: {error}");
                return false;
            }

            return true;
        }

        // Folder by folder, so the asset database knows each one before a script is moved into it.
        private static void CreateFolder(string folder)
        {
            if (AssetDatabase.IsValidFolder(folder))
                return;

            var parent = Path.GetDirectoryName(folder)!.Replace('\\', '/');

            CreateFolder(parent);
            AssetDatabase.CreateFolder(parent, Path.GetFileName(folder));
        }

        /// <summary>What generating <paramref name="generator"/> does to each of its scripts, one line each.</summary>
        public static IEnumerable<string> DescribeWrites(CodeGenerator generator) =>
            generator.GetScriptSpecs().Select(spec =>
            {
                var oldPath = GetGeneratedPath(generator, spec.Key);
                var path = GetScriptPath(generator, spec.FileName);

                return string.IsNullOrEmpty(oldPath) || oldPath == path ? $"Writes {path}" : $"Moves {oldPath} to {path}";
            });

        #endregion

        #region Unused Scripts

        /// <summary>The scripts <paramref name="generator"/> keeps under a key it no longer writes.</summary>
        public static List<GeneratedScript> GetUnusedScripts(CodeGenerator generator)
        {
            var keys = new HashSet<string>(generator.GetScriptSpecs().Select(spec => spec.Key));

            return generator.Scripts.Where(script => script.Script && !keys.Contains(script.Key)).ToList();
        }

        /// <summary>Deletes the scripts of <paramref name="scripts"/> and forgets them, after asking.</summary>
        public static bool DeleteScripts(CodeGenerator generator, IReadOnlyCollection<GeneratedScript> scripts)
        {
            var paths = scripts.Where(script => script.Script).Select(script => AssetDatabase.GetAssetPath(script.Script)).ToList();

            if (paths.Count > 0 && !EditorUtility.DisplayDialog("Delete Scripts",
                    $"Delete {string.Join(", ", paths)}? Assets of their classes lose their script.", "Delete", "Cancel"))
                return false;

            foreach (var path in paths)
                AssetDatabase.DeleteAsset(path);

            KeepScripts(generator, scripts);

            return true;
        }

        /// <summary>
        /// Forgets the scripts of <paramref name="scripts"/>, which stay as scripts of the game that the generator
        /// no longer writes or moves.
        /// </summary>
        public static void KeepScripts(CodeGenerator generator, IEnumerable<GeneratedScript> scripts)
        {
            foreach (var script in scripts.ToList())
                generator.RemoveScript(script.Key);

            SteamItemDefinitions.instance.SaveDefinitions();
        }

        #endregion

        #region Problems

        /// <summary>Everything that keeps <paramref name="generator"/> from generating.</summary>
        public static List<string> GetProblems(CodeGenerator generator)
        {
            var problems = new List<string>();

            CollectNameProblems("Class Name", generator.ClassName, generator.ClassNameExample, problems);
            CollectNamespaceProblems(generator.Namespace, problems);

            if (string.IsNullOrWhiteSpace(generator.OutputFolder))
                problems.Add("Output Folder is empty.");

            if (!string.IsNullOrWhiteSpace(generator.AssetMenu) && !AssetMenuPattern.IsMatch(generator.AssetMenu))
                problems.Add($"Asset Menu \"{generator.AssetMenu}\" may have only letters, digits, spaces, _, - and /.");

            generator.CollectProblems(problems);

            var unused = GetUnusedScripts(generator);

            if (unused.Count > 0)
                problems.Add($"No longer generated: {string.Join(", ", unused.Select(script => AssetDatabase.GetAssetPath(script.Script)))}. " +
                             "Delete them, or keep them as your own scripts, which this then leaves alone.");

            // The paths are checked only once the rest is right, since they are made from the names.
            if (problems.Count == 0)
                foreach (var spec in generator.GetScriptSpecs())
                    CollectPathProblems(generator, spec, problems);

            return problems;
        }

        private static void CollectPathProblems(CodeGenerator generator, ScriptSpec spec, List<string> problems)
        {
            var path = GetScriptPath(generator, spec.FileName);

            if (!path.StartsWith("Assets/"))
                problems.Add($"{path} is outside Assets, so Unity would not compile it.");
            else if (File.Exists(path) && path != GetGeneratedPath(generator, spec.Key) && !MayAdopt(generator, spec.Key, path))
                problems.Add($"{path} already exists and this did not generate it, so it is not overwritten.");
        }

        // A file there is taken over only when the generator has no script under the key yet and the file says it
        // was generated, e.g. one written before the generator kept its scripts.
        private static bool MayAdopt(CodeGenerator generator, string key, string path) =>
            !generator.GetScript(key) && File.ReadLines(path).Take(3).Any(line => line.Contains(GENERATED_MARKER));

        public static void CollectNameProblems(string label, string name, string example, List<string> problems)
        {
            if (string.IsNullOrWhiteSpace(name))
                problems.Add($"{label} is empty.");
            else if (!NamePattern.IsMatch(name))
                problems.Add($"{label} \"{name}\" is not PascalCase letters and digits, e.g. {example}.");
        }

        public static void CollectNamespaceProblems(string namespaceName, List<string> problems)
        {
            if (!string.IsNullOrWhiteSpace(namespaceName) && !NamespacePattern.IsMatch(namespaceName.Trim()))
                problems.Add($"Namespace \"{namespaceName}\" is not a C# namespace.");
        }

        #endregion

        #region Paths and Code

        /// <summary>Where <paramref name="generator"/> writes <paramref name="fileName"/>: <c>OutputFolder/fileName.cs</c>.</summary>
        public static string GetScriptPath(CodeGenerator generator, string fileName) =>
            $"{generator.OutputFolder?.Trim().Replace('\\', '/').TrimEnd('/')}/{fileName}.cs";

        /// <summary>The path of the script <paramref name="generator"/> wrote last under <paramref name="key"/>, or null.</summary>
        public static string GetGeneratedPath(CodeGenerator generator, string key)
        {
            var script = generator.GetScript(key);

            return script ? AssetDatabase.GetAssetPath(script) : null;
        }

        /// <summary>
        /// Whether the script of <paramref name="generator"/> under <paramref name="key"/> is written where its name
        /// and folder say, so the type it declares has that name.
        /// </summary>
        public static bool IsGenerated(CodeGenerator generator, string key, string fileName) =>
            GetGeneratedPath(generator, key) == GetScriptPath(generator, fileName);

        /// <summary>A type of <paramref name="generator"/>'s namespace from the global one, e.g. <c>global::Game.Rarity</c>.</summary>
        public static string GetGlobalName(CodeGenerator generator, string typeName) =>
            string.IsNullOrWhiteSpace(generator.Namespace)
                ? $"global::{typeName}"
                : $"global::{generator.Namespace.Trim()}.{typeName}";

        /// <summary>
        /// The <c>CreateAssetMenu</c> attribute of a generated asset class, named <paramref name="label"/> in the
        /// folder of <see cref="CodeGenerator.AssetMenu"/>.
        /// </summary>
        public static string GetAssetMenuAttribute(CodeGenerator generator, string label)
        {
            var folder = generator.AssetMenu?.Trim().Trim('/');
            var menuName = string.IsNullOrEmpty(folder) ? label : $"{folder}/{label}";

            return $"[global::UnityEngine.CreateAssetMenu(fileName = \"New {label}\", menuName = \"{menuName}\")]\n";
        }

        /// <summary><paramref name="code"/> one level deeper: four spaces before every line that is not empty.</summary>
        public static string Indent(string code)
        {
            var indented = new StringBuilder();

            foreach (var line in code.TrimEnd('\n').Split('\n'))
                indented.Append(line.Length == 0 ? "\n" : $"    {line}\n");

            return indented.ToString();
        }

        private static string GetHeader(CodeGenerator generator) =>
            "// <auto-generated>\n" +
            $"// {GENERATED_MARKER}{SteamItemDefinitionsWindow.TITLE}: {generator.Kind} {generator.ClassName}.\n" +
            "// Changes made here are lost when it generates again.\n" +
            "// </auto-generated>\n";

        private static string WrapInNamespace(string namespaceName, string body) =>
            string.IsNullOrWhiteSpace(namespaceName) ? body : $"namespace {namespaceName.Trim()}\n{{\n{Indent(body)}}}\n";

        #endregion
    }
}
