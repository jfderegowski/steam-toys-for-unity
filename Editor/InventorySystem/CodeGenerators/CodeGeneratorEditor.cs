using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using SteamToys.Runtime.InventorySystem.CodeGenerators;
using UnityEditor;
using UnityEditor.UIElements;
using UnityEngine;
using UnityEngine.UIElements;

namespace SteamToys.Editor.InventorySystem.CodeGenerators
{
    /// <summary>
    /// Base of the <see cref="CodeGenerator"/> inspectors: the fields, what keeps the generator from generating, the
    /// script it writes, and Generate. Generate moves the script it wrote last to the new path when the name or the
    /// folder changed, so the old one is not left behind, and it never writes over a file it did not generate.
    /// </summary>
    public abstract class CodeGeneratorEditor : UnityEditor.Editor
    {
        #region Constants

        private const string GENERATED_MARKER = "Generated by ";
        private const string SCRIPT_PROPERTY = "m_Script";
        private const string GENERATED_SCRIPT_PROPERTY = "_script";

        // PascalCase: a capital first letter keeps clear of the C# keywords, and without underscores every name has
        // one snake_case form that reads back to it.
        private static readonly Regex NamePattern = new("^[A-Z][A-Za-z0-9]*$");
        private static readonly Regex NamespacePattern = new("^[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)*$");

        #endregion

        private VisualElement _problems;
        private Label _path;
        private Button _generate;

        protected CodeGenerator Generator => (CodeGenerator)target;

        public override VisualElement CreateInspectorGUI()
        {
            var root = new VisualElement();

            AddFields(root);

            _problems = new VisualElement { style = { marginTop = 6 } };
            root.Add(_problems);

            _path = new Label { style = { marginTop = 6, unityFontStyleAndWeight = FontStyle.Italic } };
            root.Add(_path);

            _generate = new Button(Generate) { text = "Generate", style = { marginTop = 4, height = 24 } };
            root.Add(_generate);

            Refresh();
            root.TrackSerializedObjectValue(serializedObject, _ => Refresh());

            return root;
        }

        #region Generator

        /// <summary>An example of <see cref="CodeGenerator.ClassName"/>, for the message when it is not valid.</summary>
        protected abstract string ClassNameExample { get; }

        /// <summary>
        /// Adds a message for everything of this generator's own that keeps it from generating; the name, the
        /// namespace and the path are checked here.
        /// </summary>
        protected abstract void CollectProblems(List<string> problems);

        /// <summary>The code of the script inside its namespace, written for the top level.</summary>
        protected abstract string BuildBody();

        #endregion

        #region Inspector

        // The default inspector, with the script this generated shown but not edited: Generate keeps it.
        private void AddFields(VisualElement root)
        {
            var property = serializedObject.GetIterator();

            if (!property.NextVisible(true))
                return;

            do
            {
                var field = new PropertyField(property.Copy());

                if (property.propertyPath is SCRIPT_PROPERTY or GENERATED_SCRIPT_PROPERTY)
                    field.SetEnabled(false);

                root.Add(field);
            }
            while (property.NextVisible(false));

            root.Bind(serializedObject);
        }

        private void Refresh()
        {
            var problems = GetAllProblems();

            _problems.Clear();

            foreach (var problem in problems)
                _problems.Add(new HelpBox(problem, HelpBoxMessageType.Error));

            var oldPath = GetGeneratedPath(Generator);
            var path = GetScriptPath(Generator);

            _path.text = string.IsNullOrEmpty(oldPath) || oldPath == path ? $"Writes {path}" : $"Moves {oldPath} to {path}";
            _generate.SetEnabled(problems.Count == 0);
        }

        #endregion

        #region Generate

        private void Generate()
        {
            var problems = GetAllProblems();

            if (problems.Count > 0)
            {
                Debug.LogError($"{target.name}: not generated.\n{string.Join("\n", problems)}", target);
                return;
            }

            var oldPath = GetGeneratedPath(Generator);
            var path = GetScriptPath(Generator);

            CreateFolder(Path.GetDirectoryName(path)!.Replace('\\', '/'));

            // Moved, not written anew, so the script keeps its GUID and nothing is left at the old path.
            if (!string.IsNullOrEmpty(oldPath) && oldPath != path)
            {
                var error = AssetDatabase.MoveAsset(oldPath, path);

                if (!string.IsNullOrEmpty(error))
                {
                    Debug.LogError($"{target.name}: could not move {oldPath} to {path}: {error}", target);
                    return;
                }
            }

            File.WriteAllText(path, GetHeader() + "\n" + WrapInNamespace(Generator.Namespace, BuildBody()));
            AssetDatabase.ImportAsset(path);

            Generator.Script = AssetDatabase.LoadAssetAtPath<TextAsset>(path);
            EditorUtility.SetDirty(Generator);
            AssetDatabase.SaveAssetIfDirty(Generator);

            Debug.Log($"{target.name}: generated {path}.", target);
        }

        // Folder by folder, so the asset database knows each one before a script is moved into it.
        private static void CreateFolder(string folder)
        {
            if (AssetDatabase.IsValidFolder(folder))
                return;

            var parent = Path.GetDirectoryName(folder)!.Replace('\\', '/');

            CreateFolder(parent);
            AssetDatabase.CreateFolder(parent, Path.GetFileName(folder));
        }

        #endregion

        #region Problems

        // The path is checked only once the rest is right, since it is made from the name.
        private List<string> GetAllProblems()
        {
            var problems = new List<string>();

            CollectNameProblems("Class Name", Generator.ClassName, ClassNameExample, problems);
            CollectNamespaceProblems(Generator.Namespace, problems);
            CollectProblems(problems);

            if (problems.Count == 0)
                CollectPathProblems(problems);

            return problems;
        }

        private void CollectPathProblems(List<string> problems)
        {
            var path = GetScriptPath(Generator);

            if (!path.StartsWith("Assets/"))
                problems.Add($"{path} is outside Assets, so Unity would not compile it.");
            else if (File.Exists(path) && path != GetGeneratedPath(Generator) && !MayAdopt(path))
                problems.Add($"{path} already exists and this did not generate it, so it is not overwritten.");
        }

        // A file there is taken over only when this has no script yet and the file says it was generated, e.g. one
        // written before the generator kept its script.
        private bool MayAdopt(string path) =>
            !Generator.Script && File.ReadLines(path).Take(3).Any(line => line.Contains(GENERATED_MARKER));

        internal static void CollectNameProblems(string label, string name, string example, List<string> problems)
        {
            if (string.IsNullOrWhiteSpace(name))
                problems.Add($"{label} is empty.");
            else if (!NamePattern.IsMatch(name))
                problems.Add($"{label} \"{name}\" is not PascalCase letters and digits, e.g. {example}.");
        }

        internal static void CollectNamespaceProblems(string namespaceName, List<string> problems)
        {
            if (!string.IsNullOrWhiteSpace(namespaceName) && !NamespacePattern.IsMatch(namespaceName.Trim()))
                problems.Add($"Namespace \"{namespaceName}\" is not a C# namespace.");
        }

        #endregion

        #region Helpers

        /// <summary>Where <paramref name="generator"/> writes its script: <c>OutputFolder/ClassName.cs</c>.</summary>
        internal static string GetScriptPath(CodeGenerator generator)
        {
            var folder = string.IsNullOrWhiteSpace(generator.OutputFolder)
                ? Path.GetDirectoryName(AssetDatabase.GetAssetPath(generator))
                : generator.OutputFolder.Trim();

            return $"{folder?.Replace('\\', '/').TrimEnd('/')}/{generator.ClassName}.cs";
        }

        /// <summary>The path of the script <paramref name="generator"/> wrote last, or null.</summary>
        internal static string GetGeneratedPath(CodeGenerator generator) =>
            generator.Script ? AssetDatabase.GetAssetPath(generator.Script) : null;

        /// <summary>
        /// Whether the script of <paramref name="generator"/> is written where its name and folder say, so the type
        /// it declares has that name.
        /// </summary>
        internal static bool IsGenerated(CodeGenerator generator) =>
            GetGeneratedPath(generator) == GetScriptPath(generator);

        /// <summary>The type of <paramref name="generator"/> from the global namespace, e.g. <c>global::Game.Rarity</c>.</summary>
        internal static string GetGlobalName(CodeGenerator generator) =>
            string.IsNullOrWhiteSpace(generator.Namespace)
                ? $"global::{generator.ClassName}"
                : $"global::{generator.Namespace.Trim()}.{generator.ClassName}";

        /// <summary><paramref name="code"/> one level deeper: four spaces before every line that is not empty.</summary>
        protected static string Indent(string code)
        {
            var indented = new StringBuilder();

            foreach (var line in code.TrimEnd('\n').Split('\n'))
                indented.Append(line.Length == 0 ? "\n" : $"    {line}\n");

            return indented.ToString();
        }

        private string GetHeader() =>
            "// <auto-generated>\n" +
            $"// {GENERATED_MARKER}{target.GetType().Name} from {AssetDatabase.GetAssetPath(target)}.\n" +
            "// Changes made here are lost when it generates again.\n" +
            "// </auto-generated>\n";

        private static string WrapInNamespace(string namespaceName, string body) =>
            string.IsNullOrWhiteSpace(namespaceName) ? body : $"namespace {namespaceName.Trim()}\n{{\n{Indent(body)}}}\n";

        #endregion
    }
}
