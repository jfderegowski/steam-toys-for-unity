using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using SteamToys.Runtime.InventorySystem.CodeGenerators;
using SteamToys.Runtime.InventorySystem.Converters;
using UnityEditor;
using UnityEditor.UIElements;
using UnityEngine;
using UnityEngine.UIElements;

namespace SteamToys.Editor.InventorySystem.CodeGenerators
{
    /// <summary>
    /// The <see cref="TagCodeGenerator"/> inspector: its fields, what keeps it from generating, and Generate, which
    /// writes the enum to <c>OutputFolder/TagName.cs</c>. A file there that this did not write is never overwritten.
    /// </summary>
    [CustomEditor(typeof(TagCodeGenerator))]
    public class TagCodeGeneratorEditor : UnityEditor.Editor
    {
        #region Constants

        private const string GENERATED_MARKER = "Generated by TagCodeGenerator";

        // PascalCase: a capital first letter keeps clear of the C# keywords, and without underscores every name has
        // one snake_case form that reads back to it.
        private static readonly Regex NamePattern = new("^[A-Z][A-Za-z0-9]*$");
        private static readonly Regex NamespacePattern = new("^[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)*$");

        #endregion

        private VisualElement _problems;
        private Label _path;
        private Button _generate;

        public override VisualElement CreateInspectorGUI()
        {
            var root = new VisualElement();

            InspectorElement.FillDefaultInspector(root, serializedObject, this);

            _problems = new VisualElement { style = { marginTop = 6 } };
            root.Add(_problems);

            _path = new Label { style = { marginTop = 6, unityFontStyleAndWeight = FontStyle.Italic } };
            root.Add(_path);

            _generate = new Button(Generate) { text = "Generate", style = { marginTop = 4, height = 24 } };
            root.Add(_generate);

            Refresh();
            root.TrackSerializedObjectValue(serializedObject, _ => Refresh());

            return root;
        }

        private void Refresh()
        {
            var generator = (TagCodeGenerator)target;
            var problems = new List<string>();

            CollectProblems(generator, problems);

            _problems.Clear();

            foreach (var problem in problems)
                _problems.Add(new HelpBox(problem, HelpBoxMessageType.Error));

            _path.text = $"Writes {GetScriptPath(generator)}";
            _generate.SetEnabled(problems.Count == 0);
        }

        private void Generate()
        {
            var generator = (TagCodeGenerator)target;
            var problems = new List<string>();

            CollectProblems(generator, problems);

            if (problems.Count > 0)
            {
                Debug.LogError($"{generator.name}: not generated.\n{string.Join("\n", problems)}");
                return;
            }

            var path = GetScriptPath(generator);

            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, BuildCode(generator, AssetDatabase.GetAssetPath(generator)));
            AssetDatabase.ImportAsset(path);

            Debug.Log($"{generator.name}: generated {path}.", generator);
        }

        #region Code

        /// <summary>
        /// The script of the enum, e.g. <c>public enum Rarity { Common = 0, Rare = 1 }</c>, with every value at its
        /// own number.
        /// </summary>
        internal static string BuildCode(TagCodeGenerator generator, string sourcePath)
        {
            var hasNamespace = !string.IsNullOrWhiteSpace(generator.Namespace);
            var indent = hasNamespace ? "    " : string.Empty;
            var code = new StringBuilder();

            code.Append("// <auto-generated>\n");
            code.Append($"// {GENERATED_MARKER} from {sourcePath}.\n");
            code.Append("// Changes made here are lost when it generates again.\n");
            code.Append("// </auto-generated>\n\n");

            if (hasNamespace)
                code.Append($"namespace {generator.Namespace.Trim()}\n{{\n");

            code.Append($"{indent}/// <summary>Values of the Steam tag <c>{generator.TagName.ToSnakeCase()}</c>.</summary>\n");
            code.Append($"{indent}public enum {generator.TagName}\n{indent}{{\n");

            foreach (var value in generator.Values.Where(value => value != null))
                code.Append($"{indent}    {value.Name} = {value.Number},\n");

            code.Append($"{indent}}}\n");

            if (hasNamespace)
                code.Append("}\n");

            return code.ToString();
        }

        internal static string GetScriptPath(TagCodeGenerator generator)
        {
            var folder = string.IsNullOrWhiteSpace(generator.OutputFolder)
                ? Path.GetDirectoryName(AssetDatabase.GetAssetPath(generator))
                : generator.OutputFolder.Trim();

            return $"{folder?.Replace('\\', '/').TrimEnd('/')}/{generator.TagName}.cs";
        }

        #endregion

        #region Problems

        /// <summary>Adds a message for everything that keeps <paramref name="generator"/> from generating.</summary>
        internal static void CollectProblems(TagCodeGenerator generator, List<string> problems)
        {
            if (string.IsNullOrWhiteSpace(generator.TagName))
                problems.Add("Tag Name is empty.");
            else if (!NamePattern.IsMatch(generator.TagName))
                problems.Add($"Tag Name \"{generator.TagName}\" is not PascalCase letters and digits, e.g. Rarity.");

            if (!string.IsNullOrWhiteSpace(generator.Namespace) && !NamespacePattern.IsMatch(generator.Namespace.Trim()))
                problems.Add($"Namespace \"{generator.Namespace}\" is not a C# namespace.");

            CollectValueProblems(generator, problems);

            if (problems.Count > 0)
                return;

            var path = GetScriptPath(generator);

            if (!path.StartsWith("Assets/"))
                problems.Add($"{path} is outside Assets, so Unity would not compile it.");
            else if (File.Exists(path) && !File.ReadAllText(path).Contains(GENERATED_MARKER))
                problems.Add($"{path} already exists and was not generated, so it is not overwritten.");
        }

        private static void CollectValueProblems(TagCodeGenerator generator, List<string> problems)
        {
            if (generator.Values.Count == 0)
            {
                problems.Add("The tag has no values.");
                return;
            }

            var names = new HashSet<string>();
            var steamNames = new Dictionary<string, string>();

            foreach (var value in generator.Values)
            {
                if (value == null || string.IsNullOrWhiteSpace(value.Name))
                {
                    problems.Add("A value has no name.");
                    continue;
                }

                if (!NamePattern.IsMatch(value.Name))
                {
                    problems.Add($"Value \"{value.Name}\" is not PascalCase letters and digits, e.g. Legendary.");
                    continue;
                }

                if (!names.Add(value.Name))
                {
                    problems.Add($"Value {value.Name} is listed more than once.");
                    continue;
                }

                // Steam gets the snake_case name, so two names that read the same there are one value to it.
                var steamName = value.Name.ToSnakeCase();

                if (steamNames.TryGetValue(steamName, out var other))
                    problems.Add($"Values {other} and {value.Name} are both {steamName} on Steam.");
                else
                    steamNames.Add(steamName, value.Name);
            }
        }

        #endregion
    }
}
